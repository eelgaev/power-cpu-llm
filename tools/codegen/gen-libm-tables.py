#!/usr/bin/env python3
"""Generate src/libm/tables.rs from glibc 2.28 sources.

usage: gen-libm-tables.py GLIBC_SRC [LIBM_SO] > src/libm/tables.rs

GLIBC_SRC is an unpacked glibc-2.28 tree (the RHEL 8 source RPM applies no
patches to these files).  With LIBM_SO (the system
/lib64/glibc-hwcaps/power9/libm-2.28.so), every table is also checked byte
for byte against the copy inside that library.
"""
import re
import struct
import sys
from pathlib import Path

src = Path(sys.argv[1])
dbl = src / "sysdeps/ieee754/dbl-64"


def little_endian_part(text):
    start = text.index("#ifdef LITTLE_ENDI")
    return text[start:]


def int_words(body):
    return [int(v, 16) & 0xFFFFFFFF for v in re.findall(r"0x[0-9a-fA-F]+", body)]


def pairs_to_bits(words):
    assert len(words) % 2 == 0
    return [(words[k + 1] << 32) | words[k] for k in range(0, len(words), 2)]


def array_body(text, name):
    m = re.search(name + r"\s*(\[[^\]]*\])+\s*=\s*\{", text)
    assert m, name
    depth, k = 0, m.end() - 1
    for k in range(m.end() - 1, len(text)):
        depth += {"{": 1, "}": -1}.get(text[k], 0)
        if depth == 0:
            break
    return text[m.end():k]


ulog = little_endian_part((dbl / "ulog.tbl").read_text())
tables = {}
for name, count in [("Iu", 182), ("Iv", 362), ("Lu", 364), ("Lv", 724)]:
    bits = pairs_to_bits(int_words(array_body(ulog, name)))
    assert len(bits) == count, (name, len(bits))
    tables[name] = bits

uexp = little_endian_part((dbl / "uexp.tbl").read_text())
for name, count in [("coar", 712), ("fine", 1024)]:
    m = re.search(r"\}\s*" + name + r"\s*=\s*\{\s*\.i\s*=\s*\{(.*?)\}\s*\}", uexp, re.S)
    bits = pairs_to_bits(int_words(m.group(1)))
    assert len(bits) == count, (name, len(bits))
    tables[name] = bits

eexp = (dbl / "eexp.tbl").read_text()
body = array_body(eexp, "TBL2")
vals = [float.fromhex(v) for v in re.findall(r"-?0x[0-9a-fA-F.]+p[-+]?\d+", body)]
assert len(vals) == 268
tables["TBL2"] = [struct.unpack("<Q", struct.pack("<d", v))[0] for v in vals]

upow = little_endian_part((dbl / "upow.tbl").read_text())
for name, count in [("ui", 2900), ("vj", 2175)]:
    m = re.search(r"\}\s*" + name + r"\s*=\s*\{\s*\.i\s*=\s*\{(.*?)\}\s*\}", upow, re.S)
    bits = pairs_to_bits(int_words(m.group(1)))
    assert len(bits) == count, (name, len(bits))
    tables[name] = bits

flt = src / "sysdeps/ieee754/flt-32"
exp2f = (flt / "e_exp2f_data.c").read_text()
body = exp2f[exp2f.index(".tab = {"):exp2f.index(".shift_scaled")]
tables["exp2f_tab"] = [int(v, 16) for v in re.findall(r"0x[0-9a-f]{16}", body)]
assert len(tables["exp2f_tab"]) == 32

powf_log2 = (flt / "e_powf_log2_data.c").read_text()
body = powf_log2[powf_log2.index(".tab = {"):powf_log2.index(".poly = {")]
vals = [float.fromhex(v) for v in re.findall(r"-?0x[0-9a-f.]+p[-+]?\d+", body)]
assert len(vals) == 32
tables["powf_log2_tab"] = [struct.unpack("<Q", struct.pack("<d", v))[0] for v in vals]

expf_s = (src / "sysdeps/powerpc/powerpc64/power8/fpu/e_expf.S").read_text()
t = expf_s[expf_s.index(".Ttable:"):expf_s.index(".KLN2:")]
tables["expf_T"] = [int(v, 16) for v in re.findall(r"\.8byte\s+(0x[0-9a-f]+)", t)]
assert len(tables["expf_T"]) == 64

if len(sys.argv) > 2:
    so = Path(sys.argv[2]).read_bytes()
    # The libm's read-only data is mapped at file offset == virtual address
    # (first PT_LOAD), so search for each table's bytes directly.
    for name, bits in tables.items():
        blob = struct.pack("<%dQ" % len(bits), *bits)
        assert so.count(blob) >= 1, "table %s not found in %s" % (name, sys.argv[2])
        sys.stderr.write("%s: %d entries found in libm at 0x%x\n" % (name, len(bits), so.index(blob)))

rust_names = {
    "Iu": ("LOG_IU", "1/u_i for the log reduction (`Iu` in ulog.tbl)."),
    "Iv": ("LOG_IV", "1/v_j for the log reduction (`Iv` in ulog.tbl)."),
    "Lu": ("LOG_LU", "log(u_i) as high/low pairs (`Lu` in ulog.tbl)."),
    "Lv": ("LOG_LV", "log(v_j) as high/low pairs (`Lv` in ulog.tbl)."),
    "coar": ("EXP_COAR", "Coarse 2^(k/512) pairs for exp (`coar` in uexp.tbl)."),
    "fine": ("EXP_FINE", "Fine 2^(k/2^18) pairs for exp (`fine` in uexp.tbl)."),
    "TBL2": ("EXP_TBL2", "exp near multiples of 2^-6 (`TBL2` in eexp.tbl)."),
    "ui": ("POW_UI", "log reduction quadruples for pow (`ui` in upow.tbl)."),
    "vj": ("POW_VJ", "log reduction triples for pow (`vj` in upow.tbl)."),
    "exp2f_tab": ("EXP2F_TAB", "2^(i/32) - (i << 47) for powf (`__exp2f_data.tab`)."),
    "powf_log2_tab": ("POWF_LOG2_TAB", "(1/c, log2(c)) pairs for powf (`__powf_log2_data.tab`)."),
    "expf_T": ("EXPF_T", "2^(j/64) for expf (`.Ttable` in power8/fpu/e_expf.S)."),
}
print("// Generated by tools/codegen/gen-libm-tables.py from glibc 2.28; do not edit.")
print("// SPDX-License-Identifier: LGPL-2.1-or-later")
print("//! Tables of the glibc 2.28 IBM Accurate Mathematical Library, the")
print("//! POWER8 expf and the generic powf, as IEEE binary64 bit patterns.")
for key, (rname, doc) in rust_names.items():
    bits = tables[key]
    print()
    print("/// " + doc)
    print("pub(crate) static %s: [u64; %d] = [" % (rname, len(bits)))
    for k in range(0, len(bits), 4):
        print("    " + " ".join("0x%016x," % b for b in bits[k:k + 4]))
    print("];")
